WHERE c.LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
  AND h.INVOICE_NUMBER IS NULL
GROUP BY c.INVOICE_NUMBER

ORDER BY CHILD_TABLE, INVOICE_NUMBER
LIMIT 100;


-- =============================================================================
-- §4  Referential integrity — header → optional 1:1 satellites (coverage)
--     Informational: invoices missing optional child rows (not always an error)
-- =============================================================================
SELECT '§4_OPTIONAL_SATELLITE_COVERAGE' AS REPORT_SECTION;

WITH hdr AS (
    SELECT INVOICE_NUMBER, BRANCH_CODE, NET_AMOUNT, CHANNEL
    FROM SALES_DB.RAW.SALES_HEADER
    WHERE LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
      AND ($VALIDATION_BRANCH_CODE IS NULL OR BRANCH_CODE = $VALIDATION_BRANCH_CODE)
)
SELECT
    COUNT(*) AS HEADER_COUNT,
    COUNT(d.INVOICE_NUMBER) AS WITH_DELIVERY,
    COUNT(cu.INVOICE_NUMBER) AS WITH_CUSTOMER,
    COUNT(si.INVOICE_NUMBER) AS WITH_SOURCE_INFO,
    COUNT(sc.INVOICE_NUMBER) AS WITH_SOURCE_CUSTOMER,
    COUNT(*) - COUNT(d.INVOICE_NUMBER) AS HEADERS_WITHOUT_DELIVERY,
    COUNT(*) - COUNT(cu.INVOICE_NUMBER) AS HEADERS_WITHOUT_CUSTOMER
FROM hdr h
LEFT JOIN SALES_DB.RAW.SALES_DELIVERY d
    ON h.INVOICE_NUMBER = d.INVOICE_NUMBER AND d.LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
LEFT JOIN SALES_DB.RAW.SALES_CUSTOMER cu
    ON h.INVOICE_NUMBER = cu.INVOICE_NUMBER AND cu.LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
LEFT JOIN SALES_DB.RAW.SALES_SOURCE_INFO si
    ON h.INVOICE_NUMBER = si.INVOICE_NUMBER AND si.LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
LEFT JOIN SALES_DB.RAW.SALES_SOURCE_CUSTOMER_DETAIL sc
    ON h.INVOICE_NUMBER = sc.INVOICE_NUMBER AND sc.LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY;


