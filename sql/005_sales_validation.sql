-- =============================================================================
-- §3  Referential integrity — child → SALES_HEADER (orphans)
--     Expect zero rows: every child INVOICE_NUMBER exists on header for that extract day
-- =============================================================================
SELECT '§3_ORPHAN_CHILDREN' AS REPORT_SECTION;

WITH header_keys AS (
    SELECT INVOICE_NUMBER
    FROM SALES_DB.RAW.SALES_HEADER
    WHERE LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
      AND ($VALIDATION_BRANCH_CODE IS NULL OR BRANCH_CODE = $VALIDATION_BRANCH_CODE)
)
SELECT 'SALES_ITEMS' AS CHILD_TABLE, c.INVOICE_NUMBER, COUNT(*) AS ORPHAN_ROWS
FROM SALES_DB.RAW.SALES_ITEMS c
LEFT JOIN header_keys h ON c.INVOICE_NUMBER = h.INVOICE_NUMBER
WHERE c.LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
  AND ($VALIDATION_BRANCH_CODE IS NULL OR c.BRANCH_CODE = $VALIDATION_BRANCH_CODE)
  AND h.INVOICE_NUMBER IS NULL
GROUP BY c.INVOICE_NUMBER

UNION ALL
SELECT 'SALES_DELIVERY', c.INVOICE_NUMBER, COUNT(*)
FROM SALES_DB.RAW.SALES_DELIVERY c
LEFT JOIN header_keys h ON c.INVOICE_NUMBER = h.INVOICE_NUMBER
WHERE c.LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
  AND h.INVOICE_NUMBER IS NULL
GROUP BY c.INVOICE_NUMBER

UNION ALL
SELECT 'SALES_CUSTOMER', c.INVOICE_NUMBER, COUNT(*)
FROM SALES_DB.RAW.SALES_CUSTOMER c
LEFT JOIN header_keys h ON c.INVOICE_NUMBER = h.INVOICE_NUMBER
WHERE c.LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
  AND h.INVOICE_NUMBER IS NULL
GROUP BY c.INVOICE_NUMBER

UNION ALL
SELECT 'SALES_CHARGES', c.INVOICE_NUMBER, COUNT(*)
FROM SALES_DB.RAW.SALES_CHARGES c
LEFT JOIN header_keys h ON c.INVOICE_NUMBER = h.INVOICE_NUMBER
WHERE c.LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
  AND h.INVOICE_NUMBER IS NULL
GROUP BY c.INVOICE_NUMBER

UNION ALL
SELECT 'SALES_PAYMENTS', c.INVOICE_NUMBER, COUNT(*)
FROM SALES_DB.RAW.SALES_PAYMENTS c
LEFT JOIN header_keys h ON c.INVOICE_NUMBER = h.INVOICE_NUMBER
WHERE c.LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
  AND h.INVOICE_NUMBER IS NULL
GROUP BY c.INVOICE_NUMBER

UNION ALL
SELECT 'SALES_ITEM_OPTIONS', c.INVOICE_NUMBER, COUNT(*)
FROM SALES_DB.RAW.SALES_ITEM_OPTIONS c
