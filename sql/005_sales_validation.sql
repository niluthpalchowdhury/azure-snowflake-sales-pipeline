-- Header vs line grain for the validation day
SELECT '§1_HEADER_VS_LINES' AS REPORT_SECTION;

SELECT
    h.INVOICE_COUNT,
    i.LINE_COUNT,
    i.INVOICES_WITH_LINES,
    ROUND(i.LINE_COUNT / NULLIF(h.INVOICE_COUNT, 0), 2) AS AVG_LINES_PER_INVOICE
FROM (
    SELECT COUNT(*) AS INVOICE_COUNT
    FROM SALES_DB.RAW.SALES_HEADER h
    WHERE h.LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
      AND ($VALIDATION_BRANCH_CODE IS NULL OR h.BRANCH_CODE = $VALIDATION_BRANCH_CODE)
) h
CROSS JOIN (
    SELECT
        COUNT(*) AS LINE_COUNT,
        COUNT(DISTINCT INVOICE_NUMBER) AS INVOICES_WITH_LINES
    FROM SALES_DB.RAW.SALES_ITEMS i
    WHERE i.LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
      AND ($VALIDATION_BRANCH_CODE IS NULL OR i.BRANCH_CODE = $VALIDATION_BRANCH_CODE)
) i;


