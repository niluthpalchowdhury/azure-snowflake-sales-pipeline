-- §7  Invoice graph connectivity (single query view per invoice)
-- =============================================================================
SELECT '§7_INVOICE_GRAPH_SAMPLE' AS REPORT_SECTION;

WITH hdr AS (
    SELECT INVOICE_NUMBER
    FROM SALES_DB.RAW.SALES_HEADER
    WHERE LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
      AND ($VALIDATION_BRANCH_CODE IS NULL OR BRANCH_CODE = $VALIDATION_BRANCH_CODE)
    LIMIT 20
)
SELECT
    h.INVOICE_NUMBER,
    IFF(d.INVOICE_NUMBER IS NOT NULL, 1, 0) AS HAS_DELIVERY,
    IFF(cu.INVOICE_NUMBER IS NOT NULL, 1, 0) AS HAS_CUSTOMER,
    IFF(si.INVOICE_NUMBER IS NOT NULL, 1, 0) AS HAS_SOURCE_INFO,
    COALESCE(ch.CNT, 0) AS CHARGE_ROWS,
    COALESCE(pa.CNT, 0) AS PAYMENT_ROWS,
    COALESCE(it.CNT, 0) AS LINE_ROWS,
    COALESCE(io.CNT, 0) AS OPTION_ROWS
FROM hdr h
LEFT JOIN SALES_DB.RAW.SALES_DELIVERY d
    ON h.INVOICE_NUMBER = d.INVOICE_NUMBER AND d.LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
LEFT JOIN SALES_DB.RAW.SALES_CUSTOMER cu
    ON h.INVOICE_NUMBER = cu.INVOICE_NUMBER AND cu.LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
LEFT JOIN SALES_DB.RAW.SALES_SOURCE_INFO si
    ON h.INVOICE_NUMBER = si.INVOICE_NUMBER AND si.LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
LEFT JOIN (
    SELECT INVOICE_NUMBER, COUNT(*) AS CNT
    FROM SALES_DB.RAW.SALES_CHARGES
    WHERE LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
    GROUP BY INVOICE_NUMBER
) ch ON h.INVOICE_NUMBER = ch.INVOICE_NUMBER
LEFT JOIN (
    SELECT INVOICE_NUMBER, COUNT(*) AS CNT
    FROM SALES_DB.RAW.SALES_PAYMENTS
    WHERE LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
    GROUP BY INVOICE_NUMBER
) pa ON h.INVOICE_NUMBER = pa.INVOICE_NUMBER
LEFT JOIN (
    SELECT INVOICE_NUMBER, COUNT(*) AS CNT
    FROM SALES_DB.RAW.SALES_ITEMS
    WHERE LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
    GROUP BY INVOICE_NUMBER
) it ON h.INVOICE_NUMBER = it.INVOICE_NUMBER
LEFT JOIN (
    SELECT INVOICE_NUMBER, COUNT(*) AS CNT
    FROM SALES_DB.RAW.SALES_ITEM_OPTIONS
    WHERE LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
    GROUP BY INVOICE_NUMBER
) io ON h.INVOICE_NUMBER = io.INVOICE_NUMBER
ORDER BY h.INVOICE_NUMBER;


-- =============================================================================
-- §8  SALES_INVOICE_HISTORY — merge / conflict audit
--
-- These checks PASS TRIVIALLY: the table is never written by the pipeline, so
-- both queries always return zero rows. Retained for when the per-invoice merge
-- (docs/section-05) is implemented. The same applies to the
-- HISTORY_INVALID_CONFLICT_GROUP check in the section 10 summary.
-- =============================================================================
SELECT '§8_HISTORY_CONFLICT_PAIRS' AS REPORT_SECTION;

SELECT
    CONFLICT_GROUP_ID,
    INVOICE_NUMBER,
    COUNT(*) AS ROWS_IN_GROUP,
    COUNT_IF(SNAPSHOT_ROLE = 'SUPERSEDED') AS SUPERSEDED_COUNT,
    COUNT_IF(SNAPSHOT_ROLE = 'INCOMING') AS INCOMING_COUNT,
    MIN(NET_AMOUNT) AS MIN_NET,
    MAX(NET_AMOUNT) AS MAX_NET
FROM SALES_DB.RAW.SALES_INVOICE_HISTORY
WHERE REEXTRACTION_REQUESTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
GROUP BY CONFLICT_GROUP_ID, INVOICE_NUMBER
HAVING COUNT(*) <> 2
    OR SUPERSEDED_COUNT <> 1
    OR INCOMING_COUNT <> 1
    OR MIN_NET = MAX_NET
ORDER BY INVOICE_NUMBER
LIMIT 50;


SELECT '§8_HISTORY_WITHOUT_CURRENT_HEADER' AS REPORT_SECTION;

SELECT DISTINCT hist.INVOICE_NUMBER
FROM SALES_DB.RAW.SALES_INVOICE_HISTORY hist
LEFT JOIN SALES_DB.RAW.SALES_HEADER h ON hist.INVOICE_NUMBER = h.INVOICE_NUMBER
WHERE hist.REEXTRACTION_REQUESTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
  AND h.INVOICE_NUMBER IS NULL
LIMIT 50;


