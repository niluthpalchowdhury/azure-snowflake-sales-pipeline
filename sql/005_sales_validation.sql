WHERE h.LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
  AND c.CHILD_BRANCH IS NOT NULL
  AND h.BRANCH_CODE IS NOT NULL
  AND c.CHILD_BRANCH <> h.BRANCH_CODE
