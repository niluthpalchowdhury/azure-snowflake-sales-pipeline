    SELECT 'SALES_CHARGES', INVOICE_NUMBER, BRANCH_CODE
    FROM SALES_DB.RAW.SALES_CHARGES WHERE LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
