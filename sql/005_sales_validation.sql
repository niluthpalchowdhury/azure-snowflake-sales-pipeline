SELECT 'SALES_ITEMS.LINE_TAXES_DETAIL', COUNT(*)
FROM SALES_DB.RAW.SALES_ITEMS
WHERE LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
  AND LINE_TAXES_DETAIL IS NOT NULL
  AND NOT IS_ARRAY(LINE_TAXES_DETAIL);


-- =============================================================================
-- §10  PASS / FAIL summary (expect all PASS, FAIL_COUNT = 0)
-- =============================================================================
SELECT '§10_VALIDATION_SUMMARY' AS REPORT_SECTION;

WITH hdr AS (
    SELECT INVOICE_NUMBER, BRANCH_CODE
    FROM SALES_DB.RAW.SALES_HEADER
    WHERE LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
      AND ($VALIDATION_BRANCH_CODE IS NULL OR BRANCH_CODE = $VALIDATION_BRANCH_CODE)
),
checks AS (
    SELECT
        'PK_DUPLICATE_HEADERS' AS CHECK_NAME,
        COUNT(*) AS FAIL_COUNT
    FROM (
        SELECT INVOICE_NUMBER
        FROM SALES_DB.RAW.SALES_HEADER
        WHERE LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
        GROUP BY INVOICE_NUMBER
        HAVING COUNT(*) > 1
    )

    UNION ALL
    SELECT
        'ORPHAN_SALES_ITEMS',
        COUNT(*)
    FROM SALES_DB.RAW.SALES_ITEMS c
    LEFT JOIN hdr h ON c.INVOICE_NUMBER = h.INVOICE_NUMBER
    WHERE c.LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
      AND h.INVOICE_NUMBER IS NULL

    UNION ALL
    SELECT
        'ORPHAN_SALES_DELIVERY',
        COUNT(*)
    FROM SALES_DB.RAW.SALES_DELIVERY c
    LEFT JOIN hdr h ON c.INVOICE_NUMBER = h.INVOICE_NUMBER
    WHERE c.LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
      AND h.INVOICE_NUMBER IS NULL

    UNION ALL
    SELECT
        'ORPHAN_SALES_PAYMENTS',
        COUNT(*)
    FROM SALES_DB.RAW.SALES_PAYMENTS c
    LEFT JOIN hdr h ON c.INVOICE_NUMBER = h.INVOICE_NUMBER
    WHERE c.LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
      AND h.INVOICE_NUMBER IS NULL

    UNION ALL
    SELECT
        'ORPHAN_ITEM_OPTIONS',
        COUNT(*)
    FROM SALES_DB.RAW.SALES_ITEM_OPTIONS c
    LEFT JOIN SALES_DB.RAW.SALES_ITEMS i
        ON c.INVOICE_NUMBER = i.INVOICE_NUMBER
       AND c.ITEM_NUMBER = i.ITEM_NUMBER
       AND i.LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
    WHERE c.LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
      AND i.INVOICE_NUMBER IS NULL

    UNION ALL
    SELECT
        'BRANCH_MISMATCH_ITEMS',
        COUNT(*)
    FROM SALES_DB.RAW.SALES_ITEMS i
    JOIN hdr h ON i.INVOICE_NUMBER = h.INVOICE_NUMBER
    WHERE i.LAST_EXTRACTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
      AND i.BRANCH_CODE IS NOT NULL
      AND i.BRANCH_CODE <> h.BRANCH_CODE

    UNION ALL
    SELECT
        'HISTORY_INVALID_CONFLICT_GROUP',
        COUNT(*)
    FROM (
        SELECT CONFLICT_GROUP_ID, INVOICE_NUMBER
        FROM SALES_DB.RAW.SALES_INVOICE_HISTORY
        WHERE REEXTRACTION_REQUESTED_DAY = $VALIDATION_LAST_EXTRACTED_DAY
        GROUP BY CONFLICT_GROUP_ID, INVOICE_NUMBER
        HAVING COUNT(*) <> 2
            OR COUNT_IF(SNAPSHOT_ROLE = 'SUPERSEDED') <> 1
            OR COUNT_IF(SNAPSHOT_ROLE = 'INCOMING') <> 1
    )

    UNION ALL
    SELECT
        'NO_HEADERS_LOADED',
        CASE WHEN (SELECT COUNT(*) FROM hdr) = 0 THEN 1 ELSE 0 END
)
SELECT
    CHECK_NAME,
    FAIL_COUNT,
    IFF(FAIL_COUNT = 0, 'PASS', 'FAIL') AS STATUS
FROM checks
ORDER BY STATUS DESC, CHECK_NAME;
